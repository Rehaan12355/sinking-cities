"""Shared helpers: downloads with provenance logging."""
import contextlib
import datetime as dt
import fcntl
import json
import os
import time

import requests

from config import CITY, RAW, ROOT

SOURCES_JSON = ROOT / "data" / "sources.json"
UA = {"User-Agent": "sinking-cities-spaceapps/1.0"}


def _load_sources():
    if SOURCES_JSON.exists():
        return json.loads(SOURCES_JSON.read_text())
    return {}


@contextlib.contextmanager
def _sources_lock():
    """Several cities can be built at once; only one process may rewrite the log at a time."""
    with open(SOURCES_JSON.with_suffix(".lock"), "w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(lock, fcntl.LOCK_UN)


def record_source(key, *, title, url, licence, path=None, note="", status="ok"):
    """Record where a file came from. DATA_SOURCES.md is generated from this."""
    size = path.stat().st_size if path is not None and path.exists() else None
    with _sources_lock():
        _record(key, title, url, licence, path, size, note, status)


def _record(key, title, url, licence, path, size, note, status):
    src = _load_sources()
    src[f"{CITY['id']}/{key}"] = {
        "title": f"{CITY['short_name']}: {title}",
        "url": url,
        "licence": licence,
        "file": str(path.relative_to(ROOT)) if path is not None else None,
        "bytes": size,
        "retrieved": dt.date.today().isoformat(),
        "status": status,
        "note": note,
    }
    tmp = SOURCES_JSON.with_suffix(".tmp")
    tmp.write_text(json.dumps(src, indent=2, sort_keys=True))
    os.replace(tmp, SOURCES_JSON)   # swap in whole, so a reader never sees half a file


def fetch(url, name, *, params=None, force=False, tries=4, timeout=120):
    """Download url to data/raw/<name> (cached). Returns the path."""
    path = RAW / name
    if path.exists() and path.stat().st_size > 0 and not force:
        return path
    last = None
    for i in range(tries):
        try:
            r = requests.get(url, params=params, headers=UA, timeout=timeout)
            r.raise_for_status()
            path.write_bytes(r.content)
            return path
        except Exception as e:  # retry transient network errors
            last = e
            time.sleep(2 * (i + 1))
    raise RuntimeError(f"download failed: {url}: {last}")


def write_sources_md():
    src = _load_sources()
    lines = [
        "# Data sources",
        "",
        "Generated by `pipeline/common.py` from `data/sources.json`. Every number on the",
        "site traces back to a file listed here. Nothing is invented: when a source",
        "is unavailable the site says so instead of showing a value.",
        "",
        "| Key | Dataset | Retrieved | Size | Licence | Status |",
        "|---|---|---|---|---|---|",
    ]
    for k, s in sorted(src.items()):
        size = f"{s['bytes'] / 1e6:.2f} MB" if s.get("bytes") else "n/a"
        lines.append(f"| `{k}` | {s['title']} | {s['retrieved']} | {size} | {s['licence']} | {s['status']} |")
    lines += ["", "## URLs and notes", ""]
    for k, s in sorted(src.items()):
        lines.append(f"- **`{k}`**: <{s['url']}>" + (f"  \n  {s['note']}" if s.get("note") else ""))
    (ROOT / "DATA_SOURCES.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    write_sources_md()
